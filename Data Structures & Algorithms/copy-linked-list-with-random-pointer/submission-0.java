class Solution {
    public Node copyRandomList(Node head) {
                 Node cur = head;
            HashMap< Node, Node > map = new HashMap<>();
            while (cur != null) {
                Node temp = new Node(cur.val);
                map.put(cur, temp);
                cur = cur.next;
            }
            cur = head;
            while (cur != null) {
                map.get(cur).next = map.get(cur.next);
                map.get(cur).random = map.get(cur.random);
                cur = cur.next;
            }

            return  map.get(head);
    }
}
